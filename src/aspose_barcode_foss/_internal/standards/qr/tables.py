def data_codewords(version: int, ecc_letter: str) -> int:
    """Return the number of data codewords for the (version, ECC) symbol."""
    return EC_CHARACTERISTICS[(version, ecc_letter)][1]


def ec_per_block(version: int, ecc_letter: str) -> int:
    """Return the number of EC codewords per block for the (version, ECC) symbol."""
    return EC_CHARACTERISTICS[(version, ecc_letter)][2]


def block_structure(version: int, ecc_letter: str) -> list[tuple[int, int]]:
    """Return the block structure as [(count, data_per_block), ...] for the (version, ECC) symbol."""
    return EC_CHARACTERISTICS[(version, ecc_letter)][4]


def total_codewords(version: int, ecc_letter: str) -> int:
    """Return the total (data + EC) codeword count for the (version, ECC) symbol."""
    return EC_CHARACTERISTICS[(version, ecc_letter)][0]


# ---------------------------------------------------------------------------
# byte-mode character-count indicator bit length
