"""QR Code capacity tables: EC characteristics, char-count bits, remainder bits, symbol size.

Transcribes the normative error-correction characteristics table (all 160
(version, ECC) combinations), the remainder-bit list, and the byte-mode
character-count bit lengths. Provides accessors over these tables for the parser
(capacity/count-bits) and the encoder (block splitting / RS / interleaving).

The EC table is keyed by the EC-level letter ("L"/"M"/"Q"/"H") rather than the
enum, to avoid a forward dependency; callers translate enum -> .name.

References: ISO/IEC 18004 (EC characteristics, remainder bits, char-count bit lengths).
"""

