"""QR Code (ISO/IEC 18004) golden vectors (two provenance kinds).

This module holds two distinct kinds of QR fixtures with deliberately different provenance:

1. ``QR_GOLDEN_VECTORS`` -- FULL GRIDS pinned against the independent bwip-js / BWIPP
   reference encoder with pinned ``(version, EC level, mask)`` and cross-checked bit-for-bit
   against ``QrEncoder``. The byte-mode vectors use digit-free lowercase byte-forcing strings
   sized to nearly fill the (version, EC level): lowercase letters are never QR alphanumeric,
   so the reference encoder stays in pure 8-bit byte mode, and the near-full payload prevents
   it from auto-raising the EC level (it ignores the requested ``eclevel`` otherwise). The two
   single-mode grids (``numeric`` ``"01234567"`` and ``alphanumeric`` ``"AC-42"``) are pinned
   at V1-**H**: the reference encoder auto-raises the EC level for these short single-mode
   inputs, so it reproduces them only at ecc=H, and the encoder matches it bit-for-bit there.
   Each grid is the bare ``N*N`` module matrix (``N = 4*version + 17``) with no quiet zone.
   Do not hand-edit the grids.

2. ``QR_MODE_CODEWORD_VECTORS`` -- SPEC-DERIVED DATA-CODEWORD vectors. The Kanji (``点茗``)
   and byte+ECI (``"ABC"`` eci 9) inputs are not reproducible by the reference encoder (it
   uses a different mode / EC for those inputs), so it cannot serve as a bit-for-bit oracle.
   Their ground truth is instead the normative ISO/IEC 18004 §7.4.6 (Kanji 13-bit packing)
   and §7.4.2 (ECI header) bit derivations, transcribed and byte-split by hand (independent
   of the encoder), and pinned here as the expected DATA codewords.
"""

